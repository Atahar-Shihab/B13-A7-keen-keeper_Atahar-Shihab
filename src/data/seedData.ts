// Helper to generate dynamic ISO dates relative to current execution time
export const daysAgo = (days: number, hoursOffset: number = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(d.getHours() - hoursOffset);
  return d.toISOString();
};

